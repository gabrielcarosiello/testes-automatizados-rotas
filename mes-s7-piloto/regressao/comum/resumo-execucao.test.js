const { test } = require('node:test'), assert = require('node:assert/strict')
const fs = require('node:fs'), path = require('node:path'), os = require('node:os')
const { gravarEvento } = require('../../comum/registro-execucao'), { resumirEventos } = require('../../comum/resumo-execucao')
test('resumo não confunde persistência anterior com novo resultado que falhou ao salvar', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'resumo-')); t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  fs.mkdirSync(path.join(root, 'resultados', 'lote'), { recursive: true })
  const id = gravarEvento(root, 'lote', 'resultado-recebido', { codigo: '91', resultado: 'Concluída' })
  gravarEvento(root, 'lote', 'resultado-persistido', { codigo: '91', idResultado: id })
  gravarEvento(root, 'lote', 'resultado-recebido', { codigo: '91', resultado: 'Falhou' })
  const file = path.join(root, 'resultados', 'lote', 'eventos.jsonl')
  fs.appendFileSync(file, '{registro interrompido')
  const r = resumirEventos(file)
  assert.equal(r.falhas, 1); assert.equal(r.corretas, 0); assert.deepEqual(r.persistenciasPendentes, ['91']); assert.equal(r.avisos.length, 1)
})
