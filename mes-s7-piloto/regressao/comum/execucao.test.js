const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs'), path = require('node:path'), os = require('node:os')
const { lerExecucao } = require('../../comum/execucao')
const { ler } = require('../../testes/transferencias/lir-rotas')
const { selecionarRotas } = require('../../testes/transferencias/selecao-lir')
const { gravarEvento, classificarFalha } = require('../../comum/registro-execucao')
test('base recebida: planilha ativa explícita conserva 164 OK, 5 NOK, 96 NT e seleciona 101 pendentes', () => {
  const raiz = path.resolve(__dirname, '../..')
  const arquivo = path.join(__dirname, '../fixtures', 'LIR_base_10_3.xlsx'), antes = fs.readFileSync(arquivo)
  const lir = ler(raiz, arquivo)
  assert.equal(lir.rotas.filter(r => r.status === 'OK').length, 164)
  assert.equal(lir.rotas.filter(r => r.status === 'NOK').length, 5)
  assert.equal(lir.rotas.filter(r => r.status === 'NT').length, 96)
  assert.equal(selecionarRotas(lir.rotas, { testarNivelAlto: true }).length, 101)
  assert.deepEqual(fs.readFileSync(arquivo), antes)
})
test('configuração não aceita planilha fora da pasta nem esperas negativas; registro JSONL é independente de XLSX', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'execucao-')); t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  const config = valor => fs.writeFileSync(path.join(root, 'execucao.local.json'), JSON.stringify(valor))
  config({ planilha: '../fora.xlsx' }); assert.throws(() => lerExecucao(root), /dentro de planilhas/)
  config({ esperaBuscaMs: -1 }); assert.throws(() => lerExecucao(root), /0 e 10000/)
  config({}); assert.equal(lerExecucao(root).esperaVisualS7Ms, 0)
  fs.mkdirSync(path.join(root, 'resultados', 'lote'), { recursive: true })
  gravarEvento(root, 'lote', 'resultado-recebido', { codigo: '169', resultado: 'Falhou', detalhes: 'destino em nível alto' })
  const e = JSON.parse(fs.readFileSync(path.join(root, 'resultados', 'lote', 'eventos.jsonl'), 'utf8'))
  assert.equal(e.dados.codigo, '169'); assert.ok(e.id)
  assert.throws(() => gravarEvento(root, '../fora', 'etapa', {}), /inválida/)
  assert.equal(classificarFalha({ resultado: 'Falhou', etapa: 'Partida recusada: destino já em nível alto' }), 'condicao-pre-existente')
  assert.equal(classificarFalha({ resultado: 'Falhou', detalhes: 'Monitor: GET falhou ECONNREFUSED' }), 'comunicacao-ou-infraestrutura')
})
