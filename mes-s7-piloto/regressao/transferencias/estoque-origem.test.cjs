const assert = require('node:assert/strict')
const { test } = require('node:test')
const { conferirEstoqueOrigem } = require('../../testes/transferencias/estoque-origem')

test('bloqueia apenas o silo único com estoque explicitamente igual a zero', async () => {
  const conferir = silos => conferirEstoqueOrigem('RG08', async () => silos)
  assert.match((await conferir([{ val_peso_estoque: 0 }])).detalhe, /RG08 vazio/)
  assert.equal((await conferir([{ val_peso_estoque: 0.5 }])).estado, 'com-estoque')
  assert.equal((await conferir([])).estado, 'sem-cadastro')
  assert.equal((await conferir([{ val_peso_estoque: null }])).estado, 'inconclusivo')
  assert.equal((await conferir([{ val_peso_estoque: 0 }, { val_peso_estoque: 0 }])).estado, 'inconclusivo')
  const falha = await conferirEstoqueOrigem('RG08', async () => { throw new Error('dado interno da conexão') })
  assert.equal(falha.estado, 'inconclusivo')
  assert.doesNotMatch(falha.detalhe, /dado interno/)
})
